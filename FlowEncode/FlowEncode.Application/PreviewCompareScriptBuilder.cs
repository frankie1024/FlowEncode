using System;
using System.IO;
using System.Text;

namespace FlowEncode.Application;

public static class PreviewCompareScriptBuilder
{
    public static string BuildTwoSourceCompareScript(
        string sourceAPath,
        string sourceBPath,
        string? labelA = null,
        string? labelB = null)
    {
        if (string.IsNullOrWhiteSpace(sourceAPath))
        {
            throw new ArgumentException("Source A path is required.", nameof(sourceAPath));
        }

        if (string.IsNullOrWhiteSpace(sourceBPath))
        {
            throw new ArgumentException("Source B path is required.", nameof(sourceBPath));
        }

        var fullA = Path.GetFullPath(sourceAPath);
        var fullB = Path.GetFullPath(sourceBPath);
        var displayA = string.IsNullOrWhiteSpace(labelA) ? Path.GetFileName(fullA) : labelA.Trim();
        var displayB = string.IsNullOrWhiteSpace(labelB) ? Path.GetFileName(fullB) : labelB.Trim();

        var sb = new StringBuilder();
        sb.AppendLine("# Auto-generated by FlowEncode Quick Compare");
        sb.AppendLine($"# Output 0 (A): {SanitizeComment(displayA)}");
        sb.AppendLine($"# Output 1 (B): {SanitizeComment(displayB)}");
        sb.AppendLine("import os");
        sb.AppendLine("import sys");
        sb.AppendLine("import vapoursynth as vs");
        sb.AppendLine("core = vs.core");
        sb.AppendLine();
        sb.AppendLine("def _flowencode_load_source(path):");
        sb.AppendLine("    ext = os.path.splitext(path)[1].lower()");
        sb.AppendLine("    if ext in ('.vpy', '.py'):");
        sb.AppendLine("        prev_cwd = os.getcwd()");
        sb.AppendLine("        prev_sys_path = list(sys.path)");
        sb.AppendLine("        script_dir = os.path.dirname(path)");
        sb.AppendLine("        vs.clear_outputs()");
        sb.AppendLine("        try:");
        sb.AppendLine("            if script_dir and os.path.isdir(script_dir):");
        sb.AppendLine("                os.chdir(script_dir)");
        sb.AppendLine("                sys.path.insert(0, script_dir)");
        sb.AppendLine("            with open(path, 'r', encoding='utf-8-sig') as f:");
        sb.AppendLine("                code = f.read()");
        sb.AppendLine("            ns = {'__name__': '__flowencode_compare_child__', '__file__': path, '__package__': None}");
        sb.AppendLine("            exec(compile(code, path, 'exec'), ns)");
        sb.AppendLine("            outs = sorted(vs.get_outputs().items())");
        sb.AppendLine("            for _, out in outs:");
        sb.AppendLine("                if isinstance(out, vs.VideoOutputTuple):");
        sb.AppendLine("                    return out.clip");
        sb.AppendLine("            raise RuntimeError(f'Script did not expose a video output: {path}')");
        sb.AppendLine("        finally:");
        sb.AppendLine("            os.chdir(prev_cwd)");
        sb.AppendLine("            sys.path[:] = prev_sys_path");
        sb.AppendLine("    errors = []");
        sb.AppendLine("    if hasattr(core, 'lsmas') and hasattr(core.lsmas, 'LWLibavSource'):");
        sb.AppendLine("        try:");
        sb.AppendLine("            return core.lsmas.LWLibavSource(path)");
        sb.AppendLine("        except Exception as err:");
        sb.AppendLine("            errors.append(f'lsmas: {err}')");
        sb.AppendLine("    if hasattr(core, 'ffms2') and hasattr(core.ffms2, 'Source'):");
        sb.AppendLine("        try:");
        sb.AppendLine("            return core.ffms2.Source(path)");
        sb.AppendLine("        except Exception as err:");
        sb.AppendLine("            errors.append(f'ffms2: {err}')");
        sb.AppendLine("    if hasattr(core, 'bs') and hasattr(core.bs, 'VideoSource'):");
        sb.AppendLine("        try:");
        sb.AppendLine("            return core.bs.VideoSource(path)");
        sb.AppendLine("        except Exception as err:");
        sb.AppendLine("            errors.append(f'bestsource: {err}')");
        sb.AppendLine("    detail = '; '.join(errors) if errors else 'no supported source plugin (lsmas/ffms2/bestsource) is installed'");
        sb.AppendLine("    raise RuntimeError(f'Failed to open video source {path}: {detail}')");
        sb.AppendLine();
        sb.AppendLine($"clip_a = _flowencode_load_source({ToPythonStringLiteral(fullA)})");
        sb.AppendLine($"clip_b = _flowencode_load_source({ToPythonStringLiteral(fullB)})");
        sb.AppendLine("vs.clear_outputs()");
        sb.AppendLine("clip_a.set_output(0)");
        sb.AppendLine("clip_b.set_output(1)");
        return sb.ToString();
    }

    private static string ToPythonStringLiteral(string value)
    {
        return "\"" + value
            .Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal) + "\"";
    }

    private static string SanitizeComment(string value)
    {
        return value.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
    }
}

using System;
using System.Collections.Generic;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

namespace FlowEncode.Application;

/// <summary>
/// Generates a lightweight local <c>vapoursynth.pyi</c> stub from runtime introspection so Python LSPs
/// (such as Jedi) provide accurate completions, hover docs, and signature help for dynamic plugins and chained VideoNode calls.
/// </summary>
public static partial class VapourSynthStubGenerator
{
    private static readonly Regex IdentifierRegex = new(@"^[A-Za-z_][A-Za-z0-9_]*$", RegexOptions.Compiled);

    private static readonly HashSet<string> PythonKeywords = new(StringComparer.Ordinal)
    {
        "False", "None", "True", "and", "as", "assert", "async", "await", "break",
        "class", "continue", "def", "del", "elif", "else", "except", "finally",
        "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
        "not", "or", "pass", "raise", "return", "try", "while", "with", "yield"
    };

    public static string GenerateStub(VapourSynthLanguageFeaturesSnapshot snapshot)
    {
        ArgumentNullException.ThrowIfNull(snapshot);

        var sb = new StringBuilder(16 * 1024);
        sb.AppendLine("# Auto-generated by FlowEncode from active VapourSynth runtime.");
        sb.AppendLine("from typing import Any, Callable, Iterator, Mapping, Optional, Sequence, Tuple, Union");
        sb.AppendLine();

        var constants = snapshot.VsConstants ?? [];
        if (constants.Count > 0)
        {
            foreach (var constant in constants)
            {
                if (!IsSafeIdentifier(constant.Name))
                {
                    continue;
                }

                sb.AppendLine($"{constant.Name}: int");
            }

            sb.AppendLine();
        }

        var namespaces = snapshot.Namespaces ?? [];
        foreach (var ns in namespaces)
        {
            if (!IsSafeIdentifier(ns.Name))
            {
                continue;
            }

            EmitPluginClass(sb, ns, boundToClip: false);
            EmitPluginClass(sb, ns, boundToClip: true);
        }

        sb.AppendLine("class VideoFormat:");
        sb.AppendLine("    id: int");
        sb.AppendLine("    name: str");
        sb.AppendLine("    color_family: int");
        sb.AppendLine("    sample_type: int");
        sb.AppendLine("    bits_per_sample: int");
        sb.AppendLine("    bytes_per_sample: int");
        sb.AppendLine("    num_planes: int");
        sb.AppendLine("    subsampling_w: int");
        sb.AppendLine("    subsampling_h: int");
        sb.AppendLine();

        sb.AppendLine("class VideoFrame:");
        sb.AppendLine("    width: int");
        sb.AppendLine("    height: int");
        sb.AppendLine("    format: VideoFormat");
        sb.AppendLine("    props: Mapping[str, Any]");
        sb.AppendLine("    def __getitem__(self, index: int) -> Any: ...");
        sb.AppendLine();

        sb.AppendLine("class VideoNode:");
        sb.AppendLine("    width: int");
        sb.AppendLine("    height: int");
        sb.AppendLine("    format: VideoFormat");
        sb.AppendLine("    fps: Any");
        sb.AppendLine("    fps_num: int");
        sb.AppendLine("    fps_den: int");
        sb.AppendLine("    num_frames: int");
        sb.AppendLine("    def set_output(self, index: int = 0, alpha: Optional['VideoNode'] = None, alt_output: int = 0) -> None: ...");
        sb.AppendLine("    def get_frame(self, n: int) -> VideoFrame: ...");
        sb.AppendLine("    def frames(self, prefetch: Optional[int] = None, backlog: Optional[int] = None, close: bool = False) -> Iterator[VideoFrame]: ...");
        sb.AppendLine("    def __getitem__(self, index: Union[int, slice]) -> 'VideoNode': ...");
        sb.AppendLine("    def __add__(self, other: 'VideoNode') -> 'VideoNode': ...");
        sb.AppendLine("    def __mul__(self, count: int) -> 'VideoNode': ...");
        sb.AppendLine("    def __len__(self) -> int: ...");

        foreach (var ns in namespaces)
        {
            if (!IsSafeIdentifier(ns.Name))
            {
                continue;
            }

            sb.AppendLine($"    {ns.Name}: _BoundPlugin_{ns.Name}");
        }

        sb.AppendLine();
        sb.AppendLine("class Core:");
        sb.AppendLine("    num_threads: int");
        sb.AppendLine("    max_cache_size: int");
        sb.AppendLine("    def version(self) -> str: ...");
        sb.AppendLine("    def plugins(self) -> Iterator[Any]: ...");

        foreach (var ns in namespaces)
        {
            if (!IsSafeIdentifier(ns.Name))
            {
                continue;
            }

            sb.AppendLine($"    {ns.Name}: _Plugin_{ns.Name}");
        }

        sb.AppendLine();
        sb.AppendLine("core: Core");
        sb.AppendLine("def get_outputs() -> Mapping[int, Any]: ...");
        sb.AppendLine("def clear_outputs() -> None: ...");
        sb.AppendLine("def get_output(index: int = 0) -> Any: ...");
        return sb.ToString();
    }

    public static string ComputeContentHash(string content)
    {
        var bytes = SHA256.HashData(Encoding.UTF8.GetBytes(content ?? string.Empty));
        return Convert.ToHexString(bytes);
    }

    private static void EmitPluginClass(StringBuilder sb, VapourSynthPluginNamespaceDescriptor ns, bool boundToClip)
    {
        var classPrefix = boundToClip ? "_BoundPlugin_" : "_Plugin_";
        sb.AppendLine($"class {classPrefix}{ns.Name}:");
        var emittedAny = false;
        foreach (var func in ns.Functions)
        {
            if (!IsSafeIdentifier(func.Name))
            {
                continue;
            }

            emittedAny = true;
            var paramList = BuildStubParameters(func.Parameters, skipFirstClipParameter: boundToClip);
            var doc = EscapeDocstring(string.IsNullOrWhiteSpace(func.Documentation) ? ns.DisplayName : func.Documentation);
            sb.AppendLine($"    def {func.Name}(self{paramList}) -> 'VideoNode':");
            if (!string.IsNullOrEmpty(doc))
            {
                sb.AppendLine($"        \"{doc}\"");
            }
            sb.AppendLine("        ...");
        }

        if (!emittedAny)
        {
            sb.AppendLine("    ...");
        }

        sb.AppendLine();
    }

    private static string BuildStubParameters(
        IReadOnlyList<VapourSynthFunctionParameterDescriptor>? parameters,
        bool skipFirstClipParameter)
    {
        if (parameters is null || parameters.Count == 0)
        {
            return ", *args: Any, **kwargs: Any";
        }

        var parts = new List<string>(parameters.Count + 1);
        var startIndex = 0;
        if (skipFirstClipParameter && parameters.Count > 0)
        {
            var firstName = parameters[0].Name;
            if (string.Equals(firstName, "clip", StringComparison.OrdinalIgnoreCase)
                || string.Equals(firstName, "clips", StringComparison.OrdinalIgnoreCase)
                || string.Equals(firstName, "input", StringComparison.OrdinalIgnoreCase))
            {
                startIndex = 1;
            }
        }

        var seenNames = new HashSet<string>(StringComparer.Ordinal);
        var hasVarKwargs = false;
        for (var i = startIndex; i < parameters.Count; i++)
        {
            var rawLabel = parameters[i].Label?.Trim() ?? string.Empty;
            var name = parameters[i].Name?.Trim() ?? string.Empty;

            if (rawLabel.StartsWith("**", StringComparison.Ordinal))
            {
                hasVarKwargs = true;
                parts.Add("**kwargs: Any");
                continue;
            }

            if (rawLabel.StartsWith("*", StringComparison.Ordinal))
            {
                if (rawLabel == "*")
                {
                    parts.Add("*");
                }
                else
                {
                    parts.Add("*args: Any");
                }
                continue;
            }

            if (!IsSafeIdentifier(name) || !seenNames.Add(name))
            {
                continue;
            }

            parts.Add($"{name}: Any = ...");
        }

        if (!hasVarKwargs)
        {
            parts.Add("**kwargs: Any");
        }

        return parts.Count == 0 ? string.Empty : ", " + string.Join(", ", parts);
    }

    private static bool IsSafeIdentifier(string? value)
    {
        return !string.IsNullOrWhiteSpace(value)
            && IdentifierRegex.IsMatch(value)
            && !PythonKeywords.Contains(value);
    }

    private static string EscapeDocstring(string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return string.Empty;
        }

        return text
            .Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "'", StringComparison.Ordinal)
            .Replace("\r", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal)
            .Trim();
    }
}
